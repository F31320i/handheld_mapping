#!/usr/bin/env python3
"""Convert a camera_calibration YAML into vikit's (fast_livo's) parameter file.

camera_calibration writes an OpenCV-format file with camera_matrix,
distortion_coefficients, image_width, image_height. FAST-LIVO2 reads a flat
ros__parameters file with cam_fx/cam_fy/cam_cx/cam_cy and (unused for the
Pinhole model) cam_d0..cam_d3, loaded into parameter_blackboard.

Note the image size: vikit uses scale=1.0 and the width/height you calibrated
at. Calibrate at the resolution the mapping launch actually runs (640x480); if
you calibrated at another size, re-run it rather than rescaling.

Usage:
  ros2 run handheld_mapping camera_calib_to_livo2.py \
      --calib ~/.ros/camera_info/c310_640x480.yaml \
      --out src/handheld_mapping/config/camera_c310.yaml

  # the same numbers as the flat key block FAST-Calib's qr_params.yaml wants
  ros2 run handheld_mapping camera_calib_to_livo2.py \
      --calib ~/.ros/camera_info/c310_640x480.yaml --format fastcalib
"""
import argparse
import sys

import cv2
import numpy as np


def _via_opencv(path):
    # SystemError, not cv2.error: on a YAML file with no %YAML directive the
    # binding raises `cv2.error` in C++ and surfaces it as SystemError
    # ("returned a result with an exception set"), so both have to be caught.
    try:
        fs = cv2.FileStorage(path, cv2.FILE_STORAGE_READ)
    except (cv2.error, SystemError):
        return None
    try:
        if not fs.isOpened():
            return None
        k = fs.getNode('camera_matrix').mat()
        d = fs.getNode('distortion_coefficients').mat()
        w = fs.getNode('image_width')
        h = fs.getNode('image_height')
        # camera_calibration only writes the size in some versions.
        width = int(w.real()) if not w.empty() else None
        height = int(h.real()) if not h.empty() else None
    except (cv2.error, SystemError):
        return None
    finally:
        fs.release()
    return k, d, width, height


def _via_pyyaml(path):
    import yaml
    with open(path, 'r', encoding='utf-8') as f:
        text = f.read()
    # OpenCV's own dumps start with "%YAML:1.0", which PyYAML rejects; the file
    # camera_calibration writes has no directive at all. Drop it if present.
    if text.lstrip().startswith('%YAML'):
        text = text.split('\n', 1)[1]
    doc = yaml.safe_load(text)
    if not isinstance(doc, dict) or 'camera_matrix' not in doc:
        return None

    def as_mat(node, rows=None, cols=None):
        if isinstance(node, dict):
            rows = node.get('rows', rows)
            cols = node.get('cols', cols)
            node = node.get('data')
        if node is None:
            return None
        arr = np.asarray(node, dtype=float).ravel()
        if rows and cols:
            arr = arr.reshape(int(rows), int(cols))
        return arr

    k = as_mat(doc.get('camera_matrix'), 3, 3)
    d = as_mat(doc.get('distortion_coefficients'))
    return (k, d,
            doc.get('image_width'), doc.get('image_height'))


def read_yaml(path):
    """Read either YAML flavour camera_calibration / rosbag dumps produce.

    OpenCV's FileStorage is tried first because it also reads the XML variant,
    but it refuses a YAML file without the "%YAML:1.0" directive -- which is
    exactly what cameracalibrator's ost.yaml is. Measured 2026-10-26: passing
    that file straight in raises "Input file is invalid".
    """
    got = _via_opencv(path)
    if got is None or got[0] is None:
        got = _via_pyyaml(path)
    if got is None or got[0] is None:
        raise SystemExit(f'{path} has no readable camera_matrix')
    k, d, width, height = got
    return (np.asarray(k, dtype=float).reshape(3, 3),
            np.asarray(d, dtype=float).ravel() if d is not None else [],
            int(width) if width is not None else None,
            int(height) if height is not None else None)


def emit_livo2(k, d, width, height, src):
    return f"""# Generated by camera_calib_to_livo2.py from {src}
# vikit (fast_livo) intrinsics. Pinhole model: distortion is not applied by
# FAST-LIVO2, so cam_d* is informational only.
/**:
  ros__parameters:
    cam_model: Pinhole
    cam_width: {width}
    cam_height: {height}
    scale: 1.0
    cam_fx: {k[0, 0]:.6f}
    cam_fy: {k[1, 1]:.6f}
    cam_cx: {k[0, 2]:.6f}
    cam_cy: {k[1, 2]:.6f}
    cam_d0: {d[0]:.8f}
    cam_d1: {d[1]:.8f}
    cam_d2: {d[2]:.8f}
    cam_d3: {d[3]:.8f}
"""


def emit_fastcalib(k, d, width, height, src):
    """The camera block of FAST-Calib's config/qr_params.yaml.

    Upstream takes the intrinsics as eight flat scalars, not a matrix:
    common_lib.h loadParameters() reads fx/fy/cx/cy/k1/k2/p1/p2 and
    qr_detect.hpp builds cameraMatrix [[fx,0,cx],[0,fy,cy],[0,0,1]] and
    distCoeffs [k1,k2,p1,p2,0] out of them. There is no k3 key: the fifth
    OpenCV coefficient is hardcoded to 0, so dropping it is what upstream
    expects rather than a loss. Note the defaults shipped in that file belong
    to a 1280x960 camera -- they must be replaced, not merged.
    """
    return f"""# Generated by camera_calib_to_livo2.py from {src}
# Paste into FAST-Calib's config/qr_params.yaml, replacing the eight flat keys
# (fx fy cx cy k1 k2 p1 p2). Calibrated at {width}x{height}: FAST-Calib has no
# resolution check of its own, so a mismatch here fails quietly.
fx: {k[0, 0]:.6f}
fy: {k[1, 1]:.6f}
cx: {k[0, 2]:.6f}
cy: {k[1, 2]:.6f}
k1: {d[0]:.8f}
k2: {d[1]:.8f}
p1: {d[2]:.8f}
p2: {d[3]:.8f}
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--calib', required=True)
    parser.add_argument('--out', help='write here (default: stdout)')
    parser.add_argument('--width', type=int, help='override image width')
    parser.add_argument('--height', type=int, help='override image height')
    parser.add_argument('--format', default='livo2', choices=['livo2', 'fastcalib'],
                        help='livo2 = vikit ros__parameters (default); '
                             'fastcalib = flat keys for qr_params.yaml')
    args = parser.parse_args()

    k, d, width, height = read_yaml(args.calib)
    width = args.width or width or 640
    height = args.height or height or 480
    d = list(d.ravel()) if hasattr(d, 'ravel') else list(d)
    d += [0.0] * (4 - len(d))

    if args.format == 'fastcalib':
        text = emit_fastcalib(k, d, width, height, args.calib)
    else:
        text = emit_livo2(k, d, width, height, args.calib)

    if args.out:
        with open(args.out, 'w') as fh:
            fh.write(text)
        print(f'wrote {args.out}')
        print(f'  fx {k[0, 0]:.2f}  fy {k[1, 1]:.2f}  cx {k[0, 2]:.2f}  cy {k[1, 2]:.2f}  '
              f'{width}x{height}')
    else:
        sys.stdout.write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
